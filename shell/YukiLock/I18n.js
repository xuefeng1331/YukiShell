function code() {
    var l = String(Qt.uiLanguage !== "" ? Qt.uiLanguage : (Qt.locale().name || "en")).replace(/-/g, "_");
    var p = l.split("_")[0];
    if (p === "zh")
        return /Hant|_TW|_HK|_MO/.test(l) ? "zh_TW" : "zh_CN";
    return p;
}

function tr(text) {
    var d = dicts[code()];
    if (!d || typeof text !== "string")
        return text;
    var t = d[text];
    return t !== undefined ? t : text;
}

function locale() {
    return Qt.uiLanguage !== "" ? Qt.locale(Qt.uiLanguage) : Qt.locale();
}
